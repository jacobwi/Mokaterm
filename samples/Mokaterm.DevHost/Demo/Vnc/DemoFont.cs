	/// <summary>True when the pixel at <paramref name="column"/> and <paramref name="row"/> of the glyph is set.</summary>
	public static bool IsSet(char character, int column, int row)
	{
		if (column < 0 || column >= GlyphWidth || row < 0 || row >= GlyphHeight)
		{
			return false;
		}

		string glyph = Glyphs.GetValueOrDefault(char.ToUpperInvariant(character), Unknown);

		// Every row is five characters plus the separator that keeps the table readable.
		return glyph[(row * (GlyphWidth + 1)) + column] == '1';
	}
