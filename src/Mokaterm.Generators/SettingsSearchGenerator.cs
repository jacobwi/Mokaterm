using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Mokaterm.Generators;

/// <summary>
/// Writes the settings search index of one assembly: an assembly attribute for every <c>SettingsRow</c> whose label
/// is written out in a page's markup, keyed by the page's component type. The pages stay the only place a label or a
/// description is written, and a row added to any page is found the next build without anyone listing it.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SettingsSearchGenerator : IIncrementalGenerator
{
	private const string AttributeName = "Mokaterm.UI.Common.Contributions.SettingsSearchEntryAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		IncrementalValueProvider<ProjectInfo> project = context.AnalyzerConfigOptionsProvider
			.Select(static (options, _) => ProjectInfo.From(options.GlobalOptions));

		// A project that cannot see the attribute has no settings page either; it gets no output instead of an error.
		IncrementalValueProvider<bool> canWrite = context.CompilationProvider
			.Select(static (compilation, _) => compilation.GetTypeByMetadataName(AttributeName) is not null);

		IncrementalValueProvider<ImmutableArray<RazorFile>> files = context.AdditionalTextsProvider
			.Where(static text => text.Path.EndsWith(".razor", StringComparison.OrdinalIgnoreCase))
			.Select(static (text, cancellationToken) =>
				RazorMarkupScanner.Scan(text.Path, text.GetText(cancellationToken)?.ToString() ?? "", cancellationToken))
			.Where(static file => file.Matters)
			.Collect();

		context.RegisterSourceOutput(files.Combine(project).Combine(canWrite), static (output, input) =>
		{
			((ImmutableArray<RazorFile> razorFiles, ProjectInfo info), bool attributeVisible) = input;
			if (attributeVisible && info.IsUsable && Write(razorFiles, info) is { } source)
			{
				output.AddSource("SettingsSearchIndex.g.cs", source);
			}
		});
	}

	private static string? Write(ImmutableArray<RazorFile> files, ProjectInfo project)
	{
		List<RazorFile> imports = [.. files.Where(file => file.IsImports)];
		StringBuilder source = new StringBuilder()
			.AppendLine("// <auto-generated/>")
			.AppendLine("// The settings rows of this assembly's pages, read from their markup for the settings search.");
		int written = 0;
		foreach (RazorFile page in files.Where(file => file.Rows.Count > 0 && !file.IsGeneric).OrderBy(file => file.Path, StringComparer.Ordinal))
		{
			if (RazorTypeNames.Of(page, imports, project) is not { } typeName)
			{
				continue;
			}

			foreach (SettingsRowInfo row in page.Rows)
			{
				source.Append("[assembly: global::").Append(AttributeName)
					.Append("(typeof(global::").Append(typeName).Append("), ")
					.Append(Literal(row.Section)).Append(", ")
					.Append(Literal(row.Label)).Append(", ")
					.Append(Literal(row.Description)).Append(")]")
					.AppendLine();
				written++;
			}
		}

		return written == 0 ? null : source.ToString();
	}

	private static string Literal(string? value) => value is null ? "null" : SymbolDisplay.FormatLiteral(value, quote: true);
}
